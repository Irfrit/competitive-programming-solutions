template <typename T> bool ckmin(T &a, const T &b) {
  if (b < a) {
    a = b;
    return true;
  }
  return false;
}

template <typename T> bool ckmax(T &a, const T &b) {
  if (b > a) {
    a = b;
    return true;
  }
  return false;
}

void solve() {
  int N;
  cin >> N;
  string s;
  vector<ll> cnt(5, 0);
  for (int i = 0; i < N; i++) {
    cin >> s;
    string march = "MARCH";

    auto pos = march.find(s[0]);
    if (pos != string::npos) {
      cnt[pos]++;
    }
  }
  ll result = 0;

  for (int i = 0; i < 5; i++) {
    for (int j = i + 1; j < 5; j++) {
      for (int k = j + 1; k < 5; k++) {
        result += cnt[i] * cnt[j] * cnt[k];
      }
    }
  }
  cout << result << "\n";
}

int main() {
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  int t = 1;
  // cin >> t;

  while (t--) {
    solve();
  }

  return 0;
}
