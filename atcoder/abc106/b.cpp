void solve() {
  int N;
  cin >> N;

  int ans = 0;
  for (int i = 1; i <= N; i += 2) {
    int div = 0;
    for (int j = 1; j <= i; j++) {
      if (i % j == 0) {
        div++;
      }
    }

    if (div == 8)
      ans++;
  }
  cout << ans << "\n";
}

